-- Registry event app — database schema
-- Run this once in Supabase → SQL Editor → New query → paste → Run.
--
-- Design notes:
--   * Invite codes are 8 characters from a 32-char alphabet, stored only as
--     SHA-256 hashes. A code is shown once, at creation, and is not recoverable.
--   * Nothing here is a secret. This file can live in a public repo.
--   * Access is enforced by Row Level Security, not by the browser.
--   * Failed redeem attempts are counted in the database, because the browser
--     can be tampered with and short codes need a real lockout.

create extension if not exists pgcrypto with schema extensions;

-- Supabase installs pgcrypto into the `extensions` schema. The SECURITY DEFINER
-- functions below pin their search_path, so it must include `extensions` or
-- gen_random_bytes()/digest() are not visible inside them.

-- ---------------------------------------------------------------- invites
create table if not exists public.invites (
  id         uuid primary key default gen_random_uuid(),
  code_hash  text not null unique,
  label      text,
  revoked    boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.invites enable row level security;
-- Intentionally no policies: this table is only reachable through the
-- SECURITY DEFINER functions below.

-- ---------------------------------------------------------------- members
create table if not exists public.members (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  invite_id    uuid references public.invites (id) on delete set null,
  display_name text not null check (char_length(display_name) between 1 and 40),
  joined_at    timestamptz not null default now()
);

alter table public.members enable row level security;

drop policy if exists "members read self" on public.members;
create policy "members read self" on public.members
  for select to authenticated
  using (user_id = auth.uid());

-- ------------------------------------------------------- redeem attempts
create table if not exists public.redeem_attempts (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  failures     integer not null default 0,
  window_start timestamptz not null default now(),
  locked_until timestamptz
);

alter table public.redeem_attempts enable row level security;
-- No policies: only the SECURITY DEFINER function touches this.

-- ------------------------------------------------------------ event_info
create table if not exists public.event_info (
  id         integer primary key default 1 check (id = 1),
  title      text not null default 'The event',
  body       text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.event_info enable row level security;

drop policy if exists "event readable by members" on public.event_info;
create policy "event readable by members" on public.event_info
  for select to authenticated
  using (exists (select 1 from public.members m where m.user_id = auth.uid()));

