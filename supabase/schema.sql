-- Registry event app — database schema
-- Run this once in Supabase → SQL Editor → New query → paste → Run.
--
-- Design notes:
--   * Invite codes are 8 characters from a 32-char alphabet, stored only as
--     SHA-256 hashes. A code is shown once, at creation, and is not recoverable.
--   * Nothing here is a secret. This file can live in a public repo.
--   * Access is enforced by Row Level Security, not by the browser.
--   * Failed redeem attempts are counted in the database, because the browser
--     can be tampered with and short codes need a real lockout.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- invites
create table if not exists public.invites (
  id         uuid primary key default gen_random_uuid(),
  code_hash  text not null unique,
  label      text,
  revoked    boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.invites enable row level security;
-- Intentionally no policies: this table is only reachable through the
-- SECURITY DEFINER functions below.

-- ---------------------------------------------------------------- members
create table if not exists public.members (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  invite_id    uuid references public.invites (id) on delete set null,
  display_name text not null check (char_length(display_name) between 1 and 40),
  joined_at    timestamptz not null default now()
);

alter table public.members enable row level security;

drop policy if exists "members read self" on public.members;
create policy "members read self" on public.members
  for select to authenticated
  using (user_id = auth.uid());

-- ------------------------------------------------------- redeem attempts
create table if not exists public.redeem_attempts (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  failures     integer not null default 0,
  window_start timestamptz not null default now(),
  locked_until timestamptz
);

alter table public.redeem_attempts enable row level security;
-- No policies: only the SECURITY DEFINER function touches this.

-- ------------------------------------------------------------ event_info
create table if not exists public.event_info (
  id         integer primary key default 1 check (id = 1),
  title      text not null default 'The event',
  body       text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.event_info enable row level security;

drop policy if exists "event readable by members" on public.event_info;
create policy "event readable by members" on public.event_info
  for select to authenticated
  using (exists (select 1 from public.members m where m.user_id = auth.uid()));

-- --------------------------------------------------------------- comments
create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  body       text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.comments enable row level security;

drop policy if exists "comments readable by members" on public.comments;
create policy "comments readable by members" on public.comments
  for select to authenticated
  using (exists (select 1 from public.members m where m.user_id = auth.uid()));

drop policy if exists "comments insertable by members" on public.comments;
create policy "comments insertable by members" on public.comments
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and exists (select 1 from public.members m where m.user_id = auth.uid())
  );

-- Authors are resolved from members, so a client cannot spoof a display name.
drop view if exists public.comments_with_author;
create view public.comments_with_author
  with (security_invoker = on) as
select c.id, c.body, c.created_at, m.display_name
from public.comments c
join public.members m on m.user_id = c.user_id;

-- ------------------------------------------------------- redeem_invite()
-- The name comes from the invite itself (the label you created it with), so a
-- guest only ever types a code. Returns {ok:true} or {ok:false, reason:"..."}
-- instead of raising, so that the attempt counter survives a failed guess.
-- Raising would roll the counter back and make the lockout useless.
drop function if exists public.redeem_invite(text, text);

create or replace function public.redeem_invite(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_norm    text;
  v_hash    text;
  v_invite  public.invites;
  v_name    text;
  v_attempt public.redeem_attempts;
begin
  if auth.uid() is null then
    return jsonb_build_object('ok', false, 'reason', 'not_signed_in');
  end if;

  -- Lockout: 8 failures inside 10 minutes locks this session for 15 minutes.
  select * into v_attempt
  from public.redeem_attempts
  where user_id = auth.uid();

  if found and v_attempt.locked_until is not null and v_attempt.locked_until > now() then
    return jsonb_build_object(
      'ok', false,
      'reason', 'too_many_attempts',
      'retry_after_seconds', ceil(extract(epoch from (v_attempt.locked_until - now())))
    );
  end if;

  -- Codes are compared case-insensitively, ignoring spaces and dashes, so
  -- "k7qm-2x9t", "K7QM 2X9T" and "K7QM2X9T" are the same code.
  v_norm := regexp_replace(upper(coalesce(p_code, '')), '[^A-Z0-9]', '', 'g');
  v_hash := encode(digest(v_norm, 'sha256'), 'hex');

  select * into v_invite
  from public.invites
  where code_hash = v_hash and not revoked;

  if v_invite.id is null then
    insert into public.redeem_attempts as a (user_id, failures, window_start)
    values (auth.uid(), 1, now())
    on conflict (user_id) do update
      set failures = case
            when a.window_start < now() - interval '10 minutes' then 1
            else a.failures + 1
          end,
          window_start = case
            when a.window_start < now() - interval '10 minutes' then now()
            else a.window_start
          end
    returning * into v_attempt;

    if v_attempt.failures >= 8 then
      update public.redeem_attempts
      set locked_until = now() + interval '15 minutes'
      where user_id = auth.uid();
    end if;

    return jsonb_build_object('ok', false, 'reason', 'invalid_code');
  end if;

  -- The guest's name is whatever this invite was labelled with, so the code
  -- alone identifies them. Blank labels fall back to "Guest".
  v_name := left(coalesce(nullif(btrim(v_invite.label), ''), 'Guest'), 40);

  insert into public.members (user_id, invite_id, display_name)
  values (auth.uid(), v_invite.id, v_name)
  on conflict (user_id) do update
    set display_name = excluded.display_name,
        invite_id    = excluded.invite_id;

  delete from public.redeem_attempts where user_id = auth.uid();

  return jsonb_build_object('ok', true, 'display_name', v_name);
end;
$$;

revoke all on function public.redeem_invite(text) from public;
grant execute on function public.redeem_invite(text) to authenticated;

-- ------------------------------------------------------- create_invite()
-- Generates an 8-character code, e.g. "K7QM-2X9T", and stores only its hash.
-- Alphabet is 32 characters (2-9 and A-Z minus I and O) so 5 bits map cleanly
-- to one character and nothing is visually ambiguous on paper.
-- Returns the plaintext code ONCE. Call it from the SQL Editor only:
--   select public.create_invite('Mikkel');
create or replace function public.create_invite(p_label text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_alphabet constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_bytes    bytea := gen_random_bytes(8);
  v_code     text := '';
  i          integer;
begin
  if btrim(coalesce(p_label, '')) = '' then
    raise exception 'a name is required: select public.create_invite(''Mikkel'')'
      using errcode = '22023';
  end if;

  for i in 0..7 loop
    v_code := v_code || substr(v_alphabet, 1 + (get_byte(v_bytes, i) & 31), 1);
  end loop;

  insert into public.invites (code_hash, label)
  values (
    encode(digest(v_code, 'sha256'), 'hex'),
    left(coalesce(p_label, ''), 100)
  );

  return substr(v_code, 1, 4) || '-' || substr(v_code, 5, 4);
end;
$$;

revoke all on function public.create_invite(text) from public;
revoke all on function public.create_invite(text) from authenticated;
revoke all on function public.create_invite(text) from anon;

