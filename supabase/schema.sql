-- --------------------------------------------------------------- RSVP
create table if not exists public.rsvp (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  attending  boolean,
  adults     integer check (adults   is null or adults   between 0 and 50),
  children   integer check (children is null or children between 0 and 50),
  -- Which "I bring..." boxes are ticked, even if no rows were added yet.
  categories text[] not null default '{}',
  updated_at timestamptz not null default now()
);

alter table public.rsvp enable row level security;

drop policy if exists "rsvp readable by self" on public.rsvp;
create policy "rsvp readable by self" on public.rsvp
  for select to authenticated
  using (user_id = auth.uid()
         and exists (select 1 from public.members m where m.user_id = auth.uid()));

drop policy if exists "rsvp insertable by self" on public.rsvp;
create policy "rsvp insertable by self" on public.rsvp
  for insert to authenticated
  with check (user_id = auth.uid()
              and exists (select 1 from public.members m where m.user_id = auth.uid()));

drop policy if exists "rsvp updatable by self" on public.rsvp;
create policy "rsvp updatable by self" on public.rsvp
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

