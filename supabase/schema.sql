create or replace function public.set_comment_author()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
begin
  select display_name into v_name
  from public.members
  where user_id = auth.uid();

  if v_name is null then
    raise exception 'not a member' using errcode = '28000';
  end if;

  new.user_id := auth.uid();
  new.display_name := v_name;
  return new;
end;
$$;

drop trigger if exists comments_set_author on public.comments;
create trigger comments_set_author
  before insert on public.comments
  for each row execute function public.set_comment_author();

-- Superseded by the trigger above.
drop view if exists public.comments_with_author;

-- ------------------------------------------------------- redeem_invite()
-- The name comes from the invite itself (the label you created it with), so a
-- guest only ever types a code. Returns {ok:true} or {ok:false, reason:"..."}
-- instead of raising, so that the attempt counter survives a failed guess.
-- Raising would roll the counter back and make the lockout useless.
drop function if exists public.redeem_invite(text, text);

create or replace function public.redeem_invite(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_norm    text;
  v_hash    text;
  v_invite  public.invites;
  v_name    text;
  v_attempt public.redeem_attempts;
begin
  if auth.uid() is null then
    return jsonb_build_object('ok', false, 'reason', 'not_signed_in');
  end if;

  -- Lockout: 8 failures inside 10 minutes locks this session for 15 minutes.
  select * into v_attempt
  from public.redeem_attempts
  where user_id = auth.uid();

  if found and v_attempt.locked_until is not null and v_attempt.locked_until > now() then
    return jsonb_build_object(
      'ok', false,
      'reason', 'too_many_attempts',
      'retry_after_seconds', ceil(extract(epoch from (v_attempt.locked_until - now())))
    );
  end if;

  -- Codes are compared case-insensitively, ignoring spaces and dashes, so
  -- "k7qm-2x9t", "K7QM 2X9T" and "K7QM2X9T" are the same code.
  v_norm := regexp_replace(upper(coalesce(p_code, '')), '[^A-Z0-9]', '', 'g');
  v_hash := encode(digest(v_norm, 'sha256'), 'hex');

  select * into v_invite
  from public.invites
  where code_hash = v_hash and not revoked;

  if v_invite.id is null then
    insert into public.redeem_attempts as a (user_id, failures, window_start)
    values (auth.uid(), 1, now())
    on conflict (user_id) do update
      set failures = case
            when a.window_start < now() - interval '10 minutes' then 1
            else a.failures + 1
          end,
          window_start = case
            when a.window_start < now() - interval '10 minutes' then now()
            else a.window_start
          end
    returning * into v_attempt;

    if v_attempt.failures >= 8 then
      update public.redeem_attempts
      set locked_until = now() + interval '15 minutes'
      where user_id = auth.uid();
    end if;

    return jsonb_build_object('ok', false, 'reason', 'invalid_code');
  end if;

  -- The guest's name is whatever this invite was labelled with, so the code
  -- alone identifies them. Blank labels fall back to "Guest".
  v_name := left(coalesce(nullif(btrim(v_invite.label), ''), 'Guest'), 40);

  insert into public.members (user_id, invite_id, display_name)
  values (auth.uid(), v_invite.id, v_name)
  on conflict (user_id) do update
    set display_name = excluded.display_name,
        invite_id    = excluded.invite_id;

  delete from public.redeem_attempts where user_id = auth.uid();

  return jsonb_build_object('ok', true, 'display_name', v_name);
end;
$$;

revoke all on function public.redeem_invite(text) from public;
grant execute on function public.redeem_invite(text) to authenticated;

-- ------------------------------------------------------- create_invite()
-- Generates an 8-character code, e.g. "K7QM-2X9T", and stores only its hash.
-- Alphabet is 32 characters (2-9 and A-Z minus I and O) so 5 bits map cleanly
-- to one character and nothing is visually ambiguous on paper.
-- Returns the plaintext code ONCE. Call it from the SQL Editor only:
--   select public.create_invite('Mikkel');
create or replace function public.create_invite(p_label text)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_alphabet constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v_bytes    bytea := gen_random_bytes(8);
  v_code     text := '';
  i          integer;
begin
  if btrim(coalesce(p_label, '')) = '' then
    raise exception 'a name is required: select public.create_invite(''Mikkel'')'
      using errcode = '22023';
  end if;

  for i in 0..7 loop
    v_code := v_code || substr(v_alphabet, 1 + (get_byte(v_bytes, i) & 31), 1);
  end loop;

  insert into public.invites (code_hash, label)
  values (
    encode(digest(v_code, 'sha256'), 'hex'),
    left(coalesce(p_label, ''), 100)
  );

  return substr(v_code, 1, 4) || '-' || substr(v_code, 5, 4);
end;
$$;

revoke all on function public.create_invite(text) from public;
revoke all on function public.create_invite(text) from authenticated;
revoke all on function public.create_invite(text) from anon;

